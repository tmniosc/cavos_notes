static const uint8_t *glyph_of(char c) {
    if (c >= 'a' && c <= 'z')
        c = (char)(c - 'a' + 'A');
    if (c >= 'A' && c <= 'Z')
        return font8x8[1 + (c - 'A')];
    if (c >= '0' && c <= '9')
        return font8x8[27 + (c - '0')];
    return font8x8[0];
}

int fb_init(void) {
    if (fb_request.response == NULL || fb_request.response->framebuffer_count < 1)
        return 0;

    struct limine_framebuffer *f = fb_request.response->framebuffers[0];
    fb.virt   = (volatile uint8_t *)f->address;
    fb.width  = f->width;
    fb.height = f->height;
    fb.pitch  = f->pitch;
    fb.bpp    = f->bpp;
    return 1;
}

const struct fb_info *fb_get(void) { return &fb; }

void fb_put_pixel(uint64_t x, uint64_t y, uint8_t r, uint8_t g, uint8_t b) {
    if (fb.virt == NULL || x >= fb.width || y >= fb.height)
        return;                                  /* kẹp biên: đừng ghi ngoài VRAM */

    volatile uint8_t *p = fb.virt + y * fb.pitch + x * 4;   /* pitch, không width*4 */
    p[0] = b;                                    /* BGRX: byte0=B, byte1=G, byte2=R */
    p[1] = g;
    p[2] = r;
    p[3] = 0;
}

void fb_fill_rect(uint64_t x, uint64_t y, uint64_t w, uint64_t h,
                  uint8_t r, uint8_t g, uint8_t b) {
    for (uint64_t j = 0; j < h; j++)
        for (uint64_t i = 0; i < w; i++)
            fb_put_pixel(x + i, y + j, r, g, b);
}

void fb_draw_string(uint64_t x, uint64_t y, const char *s, uint32_t scale,
                    uint8_t r, uint8_t g, uint8_t b) {
    if (scale == 0)
        scale = 1;

    for (uint64_t ci = 0; s[ci] != '\0'; ci++) {
        const uint8_t *gl = glyph_of(s[ci]);

        for (uint32_t row = 0; row < 8; row++)
            for (uint32_t col = 0; col < 8; col++)
                if (gl[row] & (0x80 >> col))
                    fb_fill_rect(x + (ci * 8 + col) * scale, y + row * scale,
                                 scale, scale, r, g, b);
    }
}
